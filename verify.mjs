import assert from 'node:assert/strict';
import {readFile,stat} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';
const root=new URL('./public/',import.meta.url);
for(const file of ['index.html','app.js','styles.css','fonts.css','asset-data.js'])assert((await stat(new URL(file,root))).size>0,`Missing ${file}`);
execFileSync(process.execPath,['--check',fileURLToPath(new URL('app.js',root))]);
const html=await readFile(new URL('index.html',root),'utf8');
assert(html.includes("LENSUP_DEFAULT_VERSION='improved'"),'The public entry should open the updated prototype.');
for(const match of html.matchAll(/(?:src|href)="([^"#]+)"/g))if(!/^(?:https?:|data:)/.test(match[1]))await stat(new URL(match[1],root));
const fonts=await readFile(new URL('fonts.css',root),'utf8');
for(const match of fonts.matchAll(/url\(([^)]+)\)/g))await stat(new URL(match[1],root));
const context=vm.createContext({});vm.runInContext(await readFile(new URL('asset-data.js',root),'utf8'),context);
for(const name of ['lake-base.jpg','lake-angle.jpg','lake-wide.jpg','city.jpg','portrait.jpg','night.jpg','landscape.jpg','lensup-logo.png','lensup-mark.png'])assert(context.LENSUP_ASSETS[name]?.startsWith('data:image/'),`Missing bundled image: ${name}`);
const appRoot={innerHTML:''};Object.assign(context,{LENSUP_DEFAULT_VERSION:'improved',document:{baseURI:'https://lensup.example/',body:{className:''},querySelector:s=>s==='#app'?appRoot:null,querySelectorAll:()=>[],addEventListener(){}},window:{scrollTo(){}},location:{search:''},localStorage:{getItem:()=>null,setItem(){}},URL,URLSearchParams,setTimeout:()=>0,console});
vm.runInContext(await readFile(new URL('app.js',root),'utf8'),context);
assert(appRoot.innerHTML.includes('data-screen="improved/signup"'),'A new visitor should start at account setup.');
console.log('Ready for Render: app syntax, entry point, styles, fonts, and all nine bundled images verified.');
